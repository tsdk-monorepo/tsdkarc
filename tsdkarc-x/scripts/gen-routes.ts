// ---------------------------------------------------------------------------
// Core types
// ---------------------------------------------------------------------------

type RouteKind = "query" | "mutate" | "stream" | "upload";

type RouteDef = {
  name: string;
  kind: RouteKind;
  comment: string;
  /**
   * Zod schema expression string, or empty string for no-schema routes.
   * No-schema routes omit `input` from the handler signature.
   */
  schema: string;
  /** Handler body. Has access to `input` (if schema) and `env`. */
  handlerBody?: string;
  /** Generator body for stream routes. */
  generatorBody?: string;
  /**
   * When true, wraps with r.use(verifyMfaMw).mutate(...)
   * Only valid for mutate kind.
   */
  useMfa?: boolean;
};

type DomainDef = {
  domain: string;
  /** Top-level TypeScript declarations (schemas, types). */
  topLevel: string[];
  routes: RouteDef[];
};

// ---------------------------------------------------------------------------
// Renderer
// ---------------------------------------------------------------------------

/**
 * Renders a single route entry inside appRouter.init({ ... }).
 * Handles schema/no-schema, all four kinds, and useMfa wrapping.
 */
function renderRoute(r: RouteDef): string {
  const hasSchema = r.schema.trim() !== "";
  // No-schema handlers have no `input` param — match real API demo style
  const handlerParams = hasSchema ? "input, env" : "_, env";
  const schemaPrefix = hasSchema ? `${r.schema}, ` : "";

  let expr: string;

  if (r.kind === "stream") {
    const genParams = hasSchema ? "input, env" : "_, env";
    const body =
      r.generatorBody ??
      `yield { done: false as const };\nyield { done: true as const };`;
    expr = `r.stream(${schemaPrefix}async function* (${genParams}) {\n      ${body}\n    })`;
  } else if (r.kind === "upload") {
    // upload always requires schema
    expr = `r.upload(${r.schema}, async (input, env) => {\n      ${r.handlerBody}\n    })`;
  } else if (r.useMfa && r.kind === "mutate") {
    // Route-level middleware pattern: r.use(mw).mutate(schema, handler)
    expr = `r.use(verifyMfaMw).mutate(${schemaPrefix}async (input, env) => {\n      ${r.handlerBody}\n    })`;
  } else if (r.kind === "query") {
    expr = `r.query(${schemaPrefix}async (${handlerParams}) => {\n      ${r.handlerBody}\n    })`;
  } else {
    // mutate
    expr = `r.mutate(${schemaPrefix}async (${handlerParams}) => {\n      ${r.handlerBody}\n    })`;
  }

  return `
    /** ${r.comment} */
    ${r.name}: ${expr},`;
}

/**
 * Renders a full domain route file.
 * @param d       Domain definition
 * @param suffix  Numeric suffix string e.g. "2", or "" for first/only repeat
 */
function renderDomainFile(d: DomainDef, suffix: string): string {
  // camelCase the domain name, then append suffix — e.g. apiKeysRoutes2
  const baseName = d.domain.replace(/-([a-z])/g, (_, c: string) =>
    c.toUpperCase()
  );
  const exportName = `${baseName}Routes${suffix}`;

  const needsRpcError = d.routes.some((r) =>
    r.handlerBody?.includes("RpcError")
  );
  const needsMfa = d.routes.some((r) => r.useMfa);

  const imports = [
    `import { z } from "zod";`,
    `import { appRouter${
      needsMfa ? ", verifyMfaMw" : ""
    } } from "../../demo/app";`,

    needsRpcError ? `import { RpcError } from '../../../src/types';` : "",
  ]
    .filter(Boolean)
    .join("\n");

  const routeBodies = d.routes.map(renderRoute).join("\n");

  return `/**
 * Routes — "${d.domain}${suffix}" domain.
 * AUTO-GENERATED by generate-complex-routes.ts
 */
${imports}

// --- Shared schemas & types ---

${d.topLevel.join("\n\n")}

// --- Route definitions ---

export const ${exportName} = appRouter.init((r, ctx) => ({${routeBodies}
}));
`;
}

