/**
 * Generates realistic, type-complex route files matching the new API syntax.
 *
 * New syntax (from real routes demo):
 *   appRouter.init((r, ctx) => ({ ... }))
 *   r.query(handler)                          — no schema
 *   r.query(schema, handler)                  — with schema
 *   r.mutate(schema, handler)
 *   r.stream(schema?, async function*(input, env) { yield ... })
 *   r.upload(schema, handler)
 *   r.use(mw).mutate(schema, handler)       — route-level middleware
 *
 * Scale:
 *   DOMAIN_REPEAT multiplies every domain N times with a numeric suffix.
 *   25 domains × ~8 routes × DOMAIN_REPEAT = total routes
 *
 * Usage:
 *   npx tsx scripts/generate-complex-routes.ts
 *   DOMAIN_REPEAT=5 npx tsx scripts/generate-complex-routes.ts
 *   DOMAIN_REPEAT=10 npx tsx scripts/generate-complex-routes.ts
 */

