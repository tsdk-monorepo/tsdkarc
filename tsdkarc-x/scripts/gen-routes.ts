function main() {
  let totalFiles = 0;
  let totalRoutes = 0;

  // Track generated exports for the master index file
  const generatedExports: { exportName: string; importPath: string }[] = [];

  for (let rep = 0; rep < DOMAIN_REPEAT; rep++) {
    // No suffix on the first (or only) repeat — cleaner output for DOMAIN_REPEAT=1
    const suffix = DOMAIN_REPEAT === 1 ? "" : String(rep);

    for (const d of DOMAINS) {
      const domainName = suffix ? `${d.domain}-${suffix}` : d.domain;
      const dir = join(OUT_DIR, domainName);
      mkdirSync(dir, { recursive: true });
      writeFileSync(
        join(dir, "index.ts"),
        renderDomainFile(d, suffix),
        "utf-8"
      );

      // Calculate export name to store for the main index.ts
      const baseName = d.domain.replace(/-([a-z])/g, (_, c: string) =>
        c.toUpperCase()
      );
      const exportName = `${baseName}Routes${suffix}`;

      generatedExports.push({
        exportName,
        importPath: `./${domainName}`,
      });

      totalRoutes += d.routes.length;
      totalFiles++;
    }

    if (DOMAIN_REPEAT > 1) {
      console.log(
        `[gen] repeat ${rep}: ${DOMAINS.length} domain files written`
      );
    }
  }

  // Generate the central index.ts file that aggregates all routes
  const imports = generatedExports
    .map((r) => `import { ${r.exportName} } from "${r.importPath}";`)
    .join("\n");

  const arrayItems = generatedExports
    .map((r) => `  ${r.exportName},`)
    .join("\n");

  const routesTypes = generatedExports
    .map(
      (r) =>
        `export type ${r.exportName[0].toUpperCase()}${r.exportName.slice(
          1
        )} = InferRouteTree<typeof ${r.exportName}>;`
    )
    .join("\n");

  const importRoutesTypes = generatedExports
    .map((r) => `  ${r.exportName[0].toUpperCase()}${r.exportName.slice(1)},`)
    .join("\n");

  const clientRoutes = generatedExports
    .map(
      (r) =>
        `  ${
          r.exportName
        }: createClient<${r.exportName[0].toUpperCase()}${r.exportName.slice(
          1
        )}>(config),`
    )
    .join("\n");

  const masterIndexContent = `/**
 * Central export for all generated routes.
 * AUTO-GENERATED by generate-complex-routes.ts
 */
import type { InferRouteTree } from "../../src/types";
${imports}

const routes = {
${arrayItems}
};

${routesTypes}

/*
import { 
${importRoutesTypes}
} from '../routes'

export const mockClient = {
 ${clientRoutes}
}
**/

export default routes;
`;

  // Write the master index file to the root of OUT_DIR
  writeFileSync(join(OUT_DIR, "index.ts"), masterIndexContent, "utf-8");

  const routesPerDomain = (totalRoutes / totalFiles).toFixed(1);
  console.log(
    `\n✅  ${totalFiles} files · ${totalRoutes} routes · ~${routesPerDomain} routes/domain`
  );
  console.log(`✅  Master routes index written to scripts/routes/index.ts`);
  console.log(`    DOMAIN_REPEAT=${DOMAIN_REPEAT}  →  set env var to scale up`);
  console.log(
    `    Example: DOMAIN_REPEAT=10 npx tsx scripts/generate-complex-routes.ts`
  );
}

main();
